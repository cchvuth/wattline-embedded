#!/usr/bin/env python3
"""The Android Auto button's icon, from android_auto.svg (the Android Auto logo, outline): ui/gen/aa_icon.c and
aa_icon.h. ic_aa: A8, recoloured when drawn as the other icons (white while off, Android Auto's blue while on);
a 36 px button as the dash's other icons, the logo drawn ~26 px tall as ic_car_panel's car (its glyph spans 21 of
the view box's 24 units, so the box is drawn at 30 px, centred). Rendered at 4x, scaled down.
Another device's: PX, SIZES and GEN as export.sh, e.g. the F133 screen's PX=1.875 SIZES=ui/assets/sizes-f133.json
GEN=ui/gen/f133.
Needs rsvg-convert (librsvg) and Pillow, e.g. in a container:
  docker run --rm -v "$PWD":/w -w /w -e PX -e SIZES -e GEN debian:stable sh -c \\
    'apt-get update -qq && apt-get install -y -qq librsvg2-bin python3-pil >/dev/null && python3 ui/assets/aa_icon.py'
"""
import json
import os
import subprocess
import tempfile

from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
# the Dash's 36 px (24 dp at 1.25 px/dp, links 1.2); another device's from its PX and its sizes file's links
# (the F133 screen: 1.875 px/dp, links 1: 45 px)
LINK = json.load(open(os.environ.get('SIZES') or os.path.join(HERE, 'sizes.json')))['link']
K = float(os.environ.get('PX', '1.25')) * LINK / 1.5
SIZE = round(36 * K)  # px, the button
BOX = round(30 * K)   # px, the view box drawn: the glyph ~26 px tall at the Dash's

with tempfile.TemporaryDirectory() as t:
    png = os.path.join(t, 'i.png')
    subprocess.run(['rsvg-convert', '-w', str(4 * BOX), '-h', str(4 * BOX), '-o', png,
                    os.path.join(HERE, 'android_auto.svg')], check=True)
    glyph = Image.open(png).convert('RGBA').getchannel('A').resize((BOX, BOX), Image.LANCZOS)
alpha = Image.new('L', (SIZE, SIZE), 0)
alpha.paste(glyph, ((SIZE - BOX) // 2, (SIZE - BOX) // 2))

data = alpha.tobytes()
gen = os.environ.get('GEN') or os.path.join(HERE, '..', 'gen')
open(os.path.join(gen, 'aa_icon.c'), 'w').write(
    '/* Generated by ui/assets/aa_icon.py from ui/assets/android_auto.svg. Do not edit. */\n'
    '#include "lvgl.h"\n#include "aa_icon.h"\n'
    f'static const uint8_t ic_aa_px[] = {{{",".join(map(str, data))}}};\n'
    f'const lv_image_dsc_t ic_aa = {{.header = {{.magic = LV_IMAGE_HEADER_MAGIC, .cf = LV_COLOR_FORMAT_A8, '
    f'.w = {SIZE}, .h = {SIZE}, .stride = {SIZE}}}, .data_size = {len(data)}, .data = ic_aa_px}};\n')
open(os.path.join(gen, 'aa_icon.h'), 'w').write(
    '/* Generated by ui/assets/aa_icon.py. Do not edit. */\n#pragma once\n#include "lvgl.h"\n'
    'extern const lv_image_dsc_t ic_aa;\n')
print('ic_aa:', SIZE, 'px')
