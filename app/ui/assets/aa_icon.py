#!/usr/bin/env python3
"""The Android Auto button's icon, from android_auto.svg (the Android Auto logo): ui/gen/aa_icon.c and aa_icon.h.
  ic_aa       the logo in its colours (ARGB8888), shown while Android Auto is on
  ic_aa_mono  one colour (A8, recoloured when drawn, as the other icons): the triangle with the arrow cut out of it
              (the arrow's legs below the triangle drawn), shown while it is off
36 px tall, as the dash's other 24 dp buttons (ic_car_panel). Rendered at 4x, then scaled down.
Needs rsvg-convert (librsvg) and Pillow, e.g. in a container:
  docker run --rm -v "$PWD":/w -w /w debian:stable sh -c \
    'apt-get update -qq && apt-get install -y -qq librsvg2-bin python3-pil >/dev/null && python3 ui/assets/aa_icon.py'
"""
import os
import re
import subprocess
import tempfile

from PIL import Image, ImageChops

HERE = os.path.dirname(os.path.abspath(__file__))
SVG = open(os.path.join(HERE, 'android_auto.svg')).read()
H = 36  # px, the button's height
VIEW = re.search(r'viewBox="([^"]+)"', SVG).group(1)


def render(svg_text, h):
    with tempfile.TemporaryDirectory() as t:
        src, png = os.path.join(t, 'i.svg'), os.path.join(t, 'i.png')
        open(src, 'w').write(svg_text)
        subprocess.run(['rsvg-convert', '-h', str(h), '-o', png, src], check=True)
        return Image.open(png).convert('RGBA')


def shape(fill_attr):   # one of the logo's paths, alone, white on nothing
    d = re.search(r'fill="%s" d="([^"]+)"' % re.escape(fill_attr), SVG, re.S).group(1)
    return f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="{VIEW}"><path fill="#fff" fill-rule="evenodd" d="{d}"/></svg>'


def arrow():   # the white chevron (the logo's #F1F1F1 path)
    d = re.search(r'fill="#F1F1F1" d="([^"]+)"', SVG, re.S).group(1)
    return f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="{VIEW}"><path fill="#fff" fill-rule="evenodd" d="{d}"/></svg>'


def fit(img):   # scaled to H tall, centred on an H x H canvas
    w = round(img.width * H / img.height)
    img = img.resize((w, H), Image.LANCZOS)
    out = Image.new('RGBA', (H, H), (0, 0, 0, 0))
    out.alpha_composite(img, ((H - w) // 2, 0))
    return out


big = 4 * H
colour = fit(render(SVG, big))
tri = render(shape('#03A9F4'), big).getchannel('A')
arr = render(arrow(), big).getchannel('A')
inv = lambda a: a.point(lambda v: 255 - v)
mono_a = ImageChops.add(ImageChops.multiply(tri, inv(arr)), ImageChops.multiply(arr, inv(tri)))   # tri xor arrow
mono = fit(Image.merge('RGBA', (mono_a, mono_a, mono_a, mono_a)))

c_out, h_out = ['/* Generated by ui/assets/aa_icon.py from ui/assets/android_auto.svg. Do not edit. */\n'
                '#include "lvgl.h"\n#include "aa_icon.h"\n'], \
               ['/* Generated by ui/assets/aa_icon.py. Do not edit. */\n#pragma once\n#include "lvgl.h"\n']


def emit(name, img, a8):
    w, h = img.size
    if a8:
        data, cf, stride = img.getchannel('A').tobytes(), 'LV_COLOR_FORMAT_A8', w
    else:
        r, g, b, a = img.split()
        data, cf, stride = Image.merge('RGBA', (b, g, r, a)).tobytes(), 'LV_COLOR_FORMAT_ARGB8888', w * 4   # BGRA
    c_out.append(f'static const uint8_t {name}_px[] = {{{",".join(map(str, data))}}};\n'
                 f'const lv_image_dsc_t {name} = {{.header = {{.magic = LV_IMAGE_HEADER_MAGIC, .cf = {cf}, '
                 f'.w = {w}, .h = {h}, .stride = {stride}}}, .data_size = {len(data)}, .data = {name}_px}};\n')
    h_out.append(f'extern const lv_image_dsc_t {name};\n')


emit('ic_aa', colour, False)
emit('ic_aa_mono', mono, True)
gen = os.path.join(HERE, '..', 'gen')
open(os.path.join(gen, 'aa_icon.c'), 'w').write(''.join(c_out))
open(os.path.join(gen, 'aa_icon.h'), 'w').write(''.join(h_out))
colour.save(os.path.join(gen, 'aa_icon_preview.png')) if os.environ.get('PREVIEW') else None
print('ic_aa, ic_aa_mono:', H, 'px')
