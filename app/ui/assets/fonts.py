#!/usr/bin/env python3
"""Embeds the Roboto faces the app's text uses (ui/fonts, Apache-2.0) as C arrays for tiny_ttf: ui/gen/roboto.c"""
import os
import sys
here = os.path.dirname(os.path.abspath(__file__))
fonts, out = os.path.join(here, '..', 'fonts'), os.path.join(here, '..', 'gen', 'roboto.c')
with open(out, 'w') as f:
    f.write('/* Generated by ui/assets/fonts.py from ui/fonts (Roboto, Apache-2.0). Do not edit. */\n#include <stddef.h>\n')
    for w in ('Light', 'Regular', 'Medium', 'Bold'):
        data = open(os.path.join(fonts, f'Roboto-{w}.ttf'), 'rb').read()
        f.write(f'const unsigned char roboto_{w.lower()}[] = {{{",".join(map(str, data))}}};\n'
                f'const size_t roboto_{w.lower()}_size = {len(data)};\n')
print(out)
