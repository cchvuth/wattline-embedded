#!/usr/bin/env python3
"""kCarActions (lib/car_actions.dart: every S3XY function, the car panel's) -> C tables for core/cmdr_msg.c: each
option an action of its own (cmdr_action_def: id, state, "Group: Name: Option"), numbered after the dash's ACT_*.
Usage: python3 -I gen_car_actions.py <repo> <outdir>   (reads the repo, writes only <outdir>)"""
import re, sys, os

repo, out = sys.argv[1], sys.argv[2]
src = open(os.path.join(repo, 'lib/car_actions.dart')).read()
table = src[src.index('const kCarActions'):]
rows = re.findall(r"^\s*CarAction\('([^']*)', '([^']*)', (\d+), \[(.*)\](, confirm: true)?\),$", table, re.M)
assert len(rows) == table.count('CarAction('), (len(rows), table.count('CarAction('))   # every row parsed
c = lambda t: '"' + t.replace('\\', '\\\\').replace('"', '\\"') + '"'
opts, acts = [], []
for group, name, wire, options, confirm in rows:
    o = re.findall(r"\((null|'[^']*'), (\d+)\)", options)
    assert o and len(o) == options.count('('), (name, options)
    acts.append((group, name, len(opts), len(o), 1 if confirm else 0))
    for label, state in o:
        word = None if label == 'null' else label[1:-1]
        assert int(wire) < 256 and int(state) < 256, (name, wire, state)
        opts.append((int(wire), int(state), f'{group}: {name}' + (f': {word}' if word else ''), word))
with open(os.path.join(out, 'car_actions_gen.h'), 'w') as f:
    f.write('/* Generated by tools/gen_car_actions.py from the Flutter app\'s lib/car_actions.dart. Do not edit. */\n')
    f.write(f'const int cmdr_car_opt_count = {len(opts)}, cmdr_car_act_count = {len(acts)};\n')
    f.write(f'const cmdr_action_def cmdr_car_opts[{len(opts)}] = {{\n')
    f.writelines(f'    {{{w}, {s}, {c(l)}}},\n' for w, s, l, _ in opts)
    f.write('};\n')
    f.write(f'const char *const cmdr_car_words[{len(opts)}] = {{\n')
    f.writelines(f'    {c(wd) if wd else "NULL"},\n' for *_, wd in opts)
    f.write('};\n')
    f.write(f'const cmdr_car_act cmdr_car_acts[{len(acts)}] = {{\n')
    f.writelines(f'    {{{c(g)}, {c(n)}, {first}, {k}, {cf}}},\n' for g, n, first, k, cf in acts)
    f.write('};\n')
print(f'car actions: {len(acts)} actions, {len(opts)} presses -> {out}/car_actions_gen.h')
